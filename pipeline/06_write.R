# Step 6: write data/plays.js for the game, plus CSVs for analysis.

GAME_TYPE_LABEL <- c(R = NA, F = "Wild Card", D = "Division Series", L = "LCS", W = "World Series")

to_js <- function(r) list(
  id = r$play_id,
  date = format(r$game_date),
  game_type = r$game_type,
  bat_team = r$bat_team, fld_team = r$fld_team,
  inning = r$inning, half = ifelse(r$inning_topbot == "Top", "Top", "Bottom"),
  outs = r$outs,
  score = list(bat = r$bat_score, fld = r$fld_score),
  runner_on_first = r$runner_on_first,
  runner = list(name = coalesce(name_of(r$runner_id), "Runner"), sprint_speed = r$sprint_speed,
                imputed = r$speed_imputed),
  batter = list(name = coalesce(name_of(r$batter), "Batter")),
  fielder = list(name = coalesce(name_of(r$fielder_id), r$pos), pos = r$pos, arm_mph = r$arm_mph,
                 imputed = r$arm_imputed),
  batted_ball = list(type = r$bb_type, x = r$x_ft, y = r$y_ft, launch_speed = r$launch_speed),
  result = ifelse(r$safe == 1, "safe", "out"),
  description = str_squish(r$des),
  play_id = r$play_id,
  clip = r$clip,
  p_model = round(r$p_model, 4)
)

pool <- pool |>
  mutate(bat_team = ifelse(inning_topbot == "Top", away_team, home_team),
         fld_team = ifelse(inning_topbot == "Top", home_team, away_team)) |>
  arrange(game_date, game_pk, at_bat_number)
js_plays <- lapply(seq_len(nrow(pool)), \(i) to_js(pool[i, ]))

meta <- list(
  demo = FALSE,
  seasons = paste(unique(range(SEASONS)), collapse = "-"),
  built = format(Sys.Date()),
  ref = ref,
  n_safe = sum(pool$safe), n_out = sum(pool$safe == 0),
  n_postseason = sum(pool$game_type != "R"),
  game_types = as.list(GAME_TYPE_LABEL[!is.na(GAME_TYPE_LABEL)])
)
fit_js <- list(K = model_fit$K, n = model_fit$n, n_out = model_fit$n_out, seasons = model_fit$seasons,
               metrics = model_fit$metrics)

js <- paste0(
  "// Generated by pipeline/run.R on ", meta$built, ". Do not edit by hand.\n",
  "window.PLAYS_META = ", toJSON(meta, auto_unbox = TRUE, digits = NA), ";\n",
  "window.RE24 = ", toJSON(re24, digits = NA), ";\n",
  "window.MODEL_FIT = ", toJSON(fit_js, auto_unbox = TRUE, digits = NA), ";\n",
  "window.PLAYS = [\n",
  paste(vapply(js_plays, \(p) toJSON(p, auto_unbox = TRUE, null = "null", na = "null", digits = NA), ""),
        collapse = ",\n"),
  "\n];\n"
)
writeLines(js, "data/plays.js", useBytes = TRUE)
message(sprintf("Wrote %d plays (%d safe, %d out, %d postseason) to data/plays.js (%.1f MB)",
                length(js_plays), meta$n_safe, meta$n_out, meta$n_postseason, file.size("data/plays.js") / 1e6))

